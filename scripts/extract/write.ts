import { mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { stringify } from "yaml";
import type { PipelineResult } from "./pipeline";

const isoDate = (d: Date) => d.toISOString().slice(0, 10);

/** Writes the edition manifest, replaces the edition's item folder, and adds new drawings. */
export async function writeEdition(root: string, result: PipelineResult): Promise<void> {
  const content = join(root, "src/content");
  const { edition } = result;

  await mkdir(join(content, "editions"), { recursive: true });
  const manifest = stringify(
    { ...edition, effectiveFrom: isoDate(edition.effectiveFrom), effectiveTo: isoDate(edition.effectiveTo) },
    { lineWidth: 0 },
  );
  await writeFile(join(content, "editions", `${edition.id}.yaml`), manifest);

  const itemDir = join(content, "items", edition.id);
  await rm(itemDir, { recursive: true, force: true });
  await mkdir(itemDir, { recursive: true });
  for (const item of result.items) {
    await writeFile(join(itemDir, `${item.id}.yaml`), stringify(item, { lineWidth: 0 }));
  }

  await mkdir(join(content, "drawings"), { recursive: true });
  for (const [id, svg] of Object.entries(result.drawings)) {
    await writeFile(join(content, "drawings", `${id}.svg`), `${svg}\n`);
  }
}

const list = (ids: string[]) => (ids.length ? ids.map((id) => `- \`${id}\``).join("\n") : "_none_");

/** Pull-request body: what needs a human first, then what changed. */
export function prSummary(result: PipelineResult, editionId: string): string {
  const attention = [
    ...result.attention.map(
      (a) => `- [ ] ${a.itemId ? `\`${a.itemId}\` ` : ""}${a.category ? `[${a.category}] ` : ""}${a.message}`,
    ),
    ...result.uncertain.map((u) => `- [ ] \`${u.itemId}\` model unsure: ${u.reason}`),
  ];
  return `# OSR edition ${editionId}

Generated by the extraction workflow. Review every item as described in [REVIEW.md](../blob/HEAD/REVIEW.md); merging publishes.

## Needs attention (${attention.length})

${attention.join("\n") || "_nothing flagged_"}

## Added (${result.diff.added.length})

${list(result.diff.added)}

## Removed (${result.diff.removed.length})

${list(result.diff.removed)}

## Changed (${result.diff.changed.length})

${list(result.diff.changed)}

## Carried over unchanged (${result.diff.carried.length})

${list(result.diff.carried)}
`;
}
